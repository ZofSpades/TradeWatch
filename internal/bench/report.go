// Write saves the result as results.json, README.md and three charts in dir.
func Write(dir string, r *Result) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	js, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	files := map[string]string{
		"results.json":   string(js) + "\n",
		"README.md":      Markdown(r),
		"throughput.svg": throughputChart(r),
		"latency.svg":    latencyChart(r),
		"lag.svg":        lagChart(r),
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func rateLabel(v float64) string {
	switch {
	case v >= 1000 && math.Mod(v, 1000) == 0:
		return fmt.Sprintf("%.0fk", v/1000)
	case v >= 1000:
		return fmt.Sprintf("%.1fk", v/1000)
	default:
		return fmt.Sprintf("%.0f", v)
	}
}

// thousands formats a non-negative number with thousands separators.
func thousands(v float64) string {
	s := fmt.Sprintf("%.0f", math.Round(v))
	var b strings.Builder
	for i, c := range s {
		if i > 0 && (len(s)-i)%3 == 0 {
			b.WriteByte(',')
		}
		b.WriteRune(c)
	}
	return b.String()
}

// duration formats seconds in the unit that suits them.
func duration(v Value) string {
	if !v.OK() {
		return "–"
	}
	s := float64(v)
	switch {
	case s < 0.001:
		return fmt.Sprintf("%.0f µs", s*1e6)
	case s < 0.1:
		return fmt.Sprintf("%.1f ms", s*1000)
	case s < 1:
		return fmt.Sprintf("%.0f ms", s*1000)
	default:
		return fmt.Sprintf("%.2f s", s)
	}
}

func mib(b float64) string { return fmt.Sprintf("%.0f", b/(1<<20)) }

// Markdown renders the report.
func Markdown(r *Result) string {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	env, dep := r.Environment, r.Deployment

	p("# Pipeline benchmark\n\n")
	p("Generated by `make bench` from %s to %s UTC", r.Started.Format("2006-01-02 15:04"), r.Finished.Format("15:04"))
	if env.Commit != "" {
		p(", at commit `%s`", env.Commit)
	}
	p(". All market data is simulated. These numbers describe this pipeline on the machine below, which also ran the load generator, Kafka, Postgres, Redis and the monitoring stack.\n\n")

	best, ok := r.Sustained()
	last := r.Steps[len(r.Steps)-1]
	switch {
	case !ok:
		p("The pipeline fell behind at the first rate offered, %s events per second.\n\n", thousands(r.Steps[0].TargetRate))
	default:
		p("**Sustained throughput: %s events per second**, published by marketsim and kept up with at the %s step. That is the highest rate at which the detectors processed at least 98%% of what was published, and neither ingest nor the detectors ended the window more than one second of traffic behind. ",
			thousands(best.Published), rateLabel(best.TargetRate))
		if best.EndToEnd.N > 0 {
			p("At that rate, an alert was stored %s after the event that triggered it at the median and %s at the 99th percentile (%s alerts).",
				duration(best.EndToEnd.P50), duration(best.EndToEnd.P99), thousands(float64(best.EndToEnd.N)))
		}
		p("\n\n")
		switch {
		case !last.KeptUp:
			p("At %s events per second the pipeline fell behind. Of %s events per second published, ingest released %s and the detectors processed %s; at the end of the window ingest was %s records behind and the detectors %s.\n\n",
				thousands(last.TargetRate), thousands(last.Published), thousands(last.Released), thousands(last.Processed),
				thousands(last.Lag["ingest"].End), thousands(last.Lag["detector"].End))
		case last.SourceLimited:
			p("At the %s step marketsim could offer only %s events per second, and the pipeline kept up, so its own limit is higher than measured here.\n\n",
				rateLabel(last.TargetRate), thousands(last.Published))
		default:
			p("The pipeline kept up with every rate offered.\n\n")
		}
	}
	p("![Events per second at each stage](throughput.svg)\n\n![Latency from an event to its stored alert](latency.svg)\n\n![Consumer lag](lag.svg)\n\n")

	p("## Throughput and lag\n\n")
	p("| Target, events/s | Published | Released by ingest | Processed by detectors | Ingest lag, end / max | Detector lag, end / max | Verdict |\n")
	p("| ---: | ---: | ---: | ---: | ---: | ---: | --- |\n")
	for _, s := range r.Steps {
		p("| %s | %s | %s | %s | %s / %s | %s / %s | %s |\n", thousands(s.TargetRate), thousands(s.Published), thousands(s.Released),
			thousands(s.Processed), thousands(s.Lag["ingest"].End), thousands(s.Lag["ingest"].Max),
			thousands(s.Lag["detector"].End), thousands(s.Lag["detector"].Max), s.Verdict())
	}

	p("\n## Latency\n\n")
	p("| Target, events/s | Alerts stored | Event to stored alert: p50 | p95 | p99 | max | Event to detector: p50 | p95 | p99 |\n")
	p("| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n")
	for _, s := range r.Steps {
		e, d := s.EndToEnd, s.EventToDetector
		p("| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", thousands(s.TargetRate), thousands(float64(s.Alerts)),
			duration(e.P50), duration(e.P95), duration(e.P99), duration(e.Max), duration(d.P50), duration(d.P95), duration(d.P99))
	}

	jobs := []string{"marketsim", "ingest", "detector", "alertsink", "api"}
	p("\n## Resources\n\n")
	p("CPU in cores and resident memory in MiB, each summed over a service's instances (%d detectors).\n\n", dep.DetectorInstances)
	p("| Target, events/s |")
	for _, j := range jobs {
		p(" CPU %s |", j)
	}
	for _, j := range jobs[1:4] {
		p(" MiB %s |", j)
	}
	p("\n| ---: |%s\n", strings.Repeat(" ---: |", len(jobs)+3))
	for _, s := range r.Steps {
		p("| %s |", thousands(s.TargetRate))
		for _, j := range jobs {
			p(" %.2f |", s.CPU[j])
		}
		for _, j := range jobs[1:4] {
			p(" %s |", mib(s.RSS[j]))
		}
		p("\n")
	}

	p("\n## Setup\n\n")
	p("- **Machine:** %s; %d logical CPUs and %.1f GiB of memory visible to Docker; kernel %s",
		env.CPU, env.LogicalCPUs, float64(env.MemoryBytes)/(1<<30), env.Kernel)
	if env.Docker != "" {
		p("; Docker %s", env.Docker)
	}
	p("; %s.\n", env.Go)
	p("- **Stack:** the compose stack as `make up` starts it: one Kafka broker, %d detector instances over %d `market_events` partitions, one ingest and one alert sink, Postgres, Redis, Prometheus, Grafana and Jaeger. ",
		dep.DetectorInstances, dep.Partitions)
	p("`deploy/compose/bench.yml` switches marketsim to publish at a fixed rate in one long session (`%s`, %d symbols) with recordings off, so that the load generator spends its CPU on publishing.", dep.Session, dep.Symbols)
	if len(dep.Injection) > 0 {
		var keys []string
		for k := range dep.Injection {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		var parts []string
		for _, k := range keys {
			parts = append(parts, fmt.Sprintf("%s %g", strings.ReplaceAll(k, "_", " "), dep.Injection[k]))
		}
		p(" Abuse is injected at these rates, per symbol per simulated hour: %s.", strings.Join(parts, ", "))
	}
	p("\n- **Method:** each rate runs %.0f s before a %.0f s measurement window. Every service instance is scraped at both ends of the window and every 2 s within it.\n", r.Warmup, r.Measure)

	p("\n## Definitions\n\n")
	p("- **Published, released, processed:** the increase of `tradewatch_marketsim_events_published_total`, `tradewatch_ingest_events_released_total` and `tradewatch_detector_events_total` over the window, divided by its length.\n")
	p("- **Event to stored alert** is exact. For every alert of the session stored in the window, it is the time Postgres inserted the alert (`first_seen_at`, its transaction's start) minus the wall-clock time marketsim published the event that triggered the alert. Quantiles use the nearest-rank method, so with fewer than 100 alerts the p99 is the maximum. All containers read the same host clock.\n")
	p("- **Event to detector** comes from the detectors' `event_latency_seconds` histograms over the window, interpolated within buckets as Prometheus's `histogram_quantile` does. The bucket bounds are at most 1.5 times apart.\n")
	p("- **Lag:** the services' consumer-lag gauges, in records, summed over instances: `end` is the last sample of the window.\n")
	p("- **Kept up:** the detectors processed at least 98%% of what marketsim published, and neither ingest nor the detectors ended the window more than one second of traffic (at least 1,000 records) behind. **Sustained** means kept up while marketsim offered at least 95%% of the target rate. The run stops at the first step that is not sustained.\n")
	return b.String()
}

// chart is a line chart over the steps, which are its x categories.
type chart struct {
	title, yLabel string
	labels        []string
	logY          bool
	format        func(float64) string
	series        []chartSeries
}

type chartSeries struct {
	name, color, dash string
	values            []Value
}

func (c chart) svg() string {
	const width, height = 680.0, 380.0
	const left, right, top, bottom = 72.0, 24.0, 70.0, 56.0
	pw, ph := width-left-right, height-top-bottom
	lo, hi := math.Inf(1), math.Inf(-1)
	for _, s := range c.series {
		for _, v := range s.values {
			if v.OK() && (!c.logY || v > 0) {
				lo, hi = math.Min(lo, float64(v)), math.Max(hi, float64(v))
			}
		}
	}
	if math.IsInf(lo, 0) {
		lo, hi = 0, 1
	}
	var ticks []float64
	if c.logY {
		lo, hi = math.Pow(10, math.Floor(math.Log10(lo))), math.Pow(10, math.Ceil(math.Log10(hi)))
		if lo == hi {
			hi *= 10
		}
		for t := lo; t <= hi*1.0001; t *= 10 {
			ticks = append(ticks, t)
		}
	} else {
		lo = 0
		step := niceStep(hi / 5)
		hi = math.Ceil(hi/step) * step
		if hi == 0 {
			hi = 1
		}
		for t := 0.0; t <= hi*1.0001; t += step {
			ticks = append(ticks, t)
		}
	}
	y := func(v float64) float64 {
		if c.logY {
			return top + (1-(math.Log10(v)-math.Log10(lo))/(math.Log10(hi)-math.Log10(lo)))*ph
		}
		return top + (1-(v-lo)/(hi-lo))*ph
	}
	n := len(c.labels)
	x := func(i int) float64 {
		if n == 1 {
			return left + pw/2
		}
		return left + float64(i)*pw/float64(n-1)
	}

	var b strings.Builder
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" width="%.0f" height="%.0f" viewBox="0 0 %.0f %.0f" font-family="Helvetica, Arial, sans-serif" font-size="12" fill="#1f2937">`+"\n",
		width, height, width, height)
	fmt.Fprintf(&b, `<rect width="%.0f" height="%.0f" fill="#ffffff"/>`+"\n", width, height)
	fmt.Fprintf(&b, `<text x="%.0f" y="24" font-size="15" font-weight="bold">%s</text>`+"\n", left, html.EscapeString(c.title))
	for _, t := range ticks {
		fmt.Fprintf(&b, `<line x1="%.1f" x2="%.1f" y1="%.1f" y2="%.1f" stroke="#e5e7eb"/>`+"\n", left, width-right, y(t), y(t))
		fmt.Fprintf(&b, `<text x="%.1f" y="%.1f" text-anchor="end" dominant-baseline="middle">%s</text>`+"\n", left-8, y(t), html.EscapeString(c.format(t)))
	}
	for i, l := range c.labels {
		fmt.Fprintf(&b, `<text x="%.1f" y="%.1f" text-anchor="middle">%s</text>`+"\n", x(i), height-bottom+20, html.EscapeString(l))
	}
	fmt.Fprintf(&b, `<text x="%.1f" y="%.1f" text-anchor="middle">target rate, events per second</text>`+"\n", left+pw/2, height-14)
	fmt.Fprintf(&b, `<text transform="translate(16 %.1f) rotate(-90)" text-anchor="middle">%s</text>`+"\n", top+ph/2, html.EscapeString(c.yLabel))
	for k, s := range c.series {
		var path strings.Builder
		pen := false
		for i, v := range s.values {
			if !v.OK() || (c.logY && v <= 0) {
				pen = false
				continue
			}
			cmd := "L"
			if !pen {
				cmd = "M"
			}
			fmt.Fprintf(&path, "%s%.1f %.1f ", cmd, x(i), y(float64(v)))
			pen = true
			fmt.Fprintf(&b, `<circle cx="%.1f" cy="%.1f" r="3.5" fill="%s"/>`+"\n", x(i), y(float64(v)), s.color)
		}
		dash := ""
		if s.dash != "" {
			dash = fmt.Sprintf(` stroke-dasharray="%s"`, s.dash)
		}
		if path.Len() > 0 {
			fmt.Fprintf(&b, `<path d="%s" fill="none" stroke="%s" stroke-width="2"%s/>`+"\n", strings.TrimSpace(path.String()), s.color, dash)
		}
		lx := left + float64(k)*150
		fmt.Fprintf(&b, `<line x1="%.1f" x2="%.1f" y1="46" y2="46" stroke="%s" stroke-width="2"%s/>`+"\n", lx, lx+22, s.color, dash)
		fmt.Fprintf(&b, `<text x="%.1f" y="46" dominant-baseline="middle">%s</text>`+"\n", lx+28, html.EscapeString(s.name))
	}
	b.WriteString("</svg>\n")
	return b.String()
}

// niceStep rounds a raw tick step up to 1, 2 or 5 times a power of ten.
func niceStep(raw float64) float64 {
	if raw <= 0 {
		return 1
	}
	p := math.Pow(10, math.Floor(math.Log10(raw)))
	for _, m := range []float64{1, 2, 5, 10} {
		if raw <= m*p {
			return m * p
		}
	}
	return 10 * p
}

func stepLabels(r *Result) []string {
	var out []string
	for _, s := range r.Steps {
		out = append(out, rateLabel(s.TargetRate))
	}
	return out
}

func pick(r *Result, f func(Step) Value) []Value {
	var out []Value
	for _, s := range r.Steps {
		out = append(out, f(s))
	}
	return out
}

func throughputChart(r *Result) string {
	return chart{
		title: "Events per second at each stage", yLabel: "events per second", labels: stepLabels(r),
		format: func(v float64) string { return rateLabel(v) },
		series: []chartSeries{
			{"target", "#9ca3af", "4 4", pick(r, func(s Step) Value { return Value(s.TargetRate) })},
			{"published", "#2563eb", "", pick(r, func(s Step) Value { return Value(s.Published) })},
			{"processed by detectors", "#16a34a", "", pick(r, func(s Step) Value { return Value(s.Processed) })},
		},
	}.svg()
}

func latencyChart(r *Result) string {
	return chart{
		title: "Latency from an event's publication", yLabel: "seconds (log scale)", labels: stepLabels(r), logY: true,
		format: func(v float64) string { return duration(Value(v)) },
		series: []chartSeries{
			{"to stored alert, p50", "#2563eb", "", pick(r, func(s Step) Value { return s.EndToEnd.P50 })},
			{"to stored alert, p99", "#dc2626", "", pick(r, func(s Step) Value { return s.EndToEnd.P99 })},
			{"to detector, p99", "#16a34a", "6 4", pick(r, func(s Step) Value { return s.EventToDetector.P99 })},
		},
	}.svg()
}

func lagChart(r *Result) string {
	return chart{
		title: "Consumer lag at the end of each window", yLabel: "records (log scale)", labels: stepLabels(r), logY: true,
		format: func(v float64) string { return thousands(v) },
		series: []chartSeries{
			{"ingest", "#ea580c", "", pick(r, func(s Step) Value { return Value(math.Max(s.Lag["ingest"].End, 1)) })},
			{"detectors", "#2563eb", "", pick(r, func(s Step) Value { return Value(math.Max(s.Lag["detector"].End, 1)) })},
			{"alert sink", "#16a34a", "6 4", pick(r, func(s Step) Value { return Value(math.Max(s.Lag["alertsink"].End, 1)) })},
		},
	}.svg()
}
