// Report is the outcome of an evaluation run.
type Report struct {
	Plan            Plan
	Symbols         int
	RulesDigest     string
	BaselinesDigest string
	GoVersion       string
	Production      *Result
	Baseline        *Result
	Sweeps          []SweepResult
}

// SweepResult is the evaluation of one parameter sweep.
type SweepResult struct {
	Sweep
	// Type is the abuse type the rule detects; Production is the parameter's
	// value in the production rule.
	Type       string
	Production string
	Points     []*Result // one per value, in order
}

func (rep *Report) seedRange(first, n int) string {
	lo := rep.Plan.FirstSeed + uint64(first)
	if n == 1 {
		return fmt.Sprint(lo)
	}
	return fmt.Sprintf("%d–%d", lo, lo+uint64(n)-1)
}

func fmtRate(r Rate) string {
	if !r.Defined() {
		return "–"
	}
	return fmt.Sprintf("%.2f (%.2f–%.2f)", r.Value, r.Lo, r.Hi)
}

func fmtNum(v float64, digits int) string {
	if math.IsNaN(v) {
		return "–"
	}
	return fmt.Sprintf("%.*f", digits, v)
}

func fmtTTD(s *TypeStats) string {
	med, ok := s.TTDQuantile(0.5)
	if !ok {
		return "–"
	}
	p90, _ := s.TTDQuantile(0.9)
	return fmt.Sprintf("%.0f s / %.0f s", med, p90)
}

func (r *Result) stats(typ string) *TypeStats {
	if s := r.ByType[typ]; s != nil {
		return s
	}
	return &TypeStats{}
}

func qualityTable(b *strings.Builder, r *Result) {
	b.WriteString("| Abuse type | Episodes | Recall | Alerts | Precision | F1 | Time to detect (median / p90) | False alerts per 100 symbol-hours without abuse |\n")
	b.WriteString("| --- | ---: | --- | ---: | --- | ---: | --- | ---: |\n")
	for _, t := range TypeNames() {
		s := r.stats(t)
		fmt.Fprintf(b, "| %s | %d | %s | %d | %s | %s | %s | %s |\n", t, s.Labels, fmtRate(s.Recall()), s.Alerts,
			fmtRate(s.Precision()), fmtNum(s.F1(), 2), fmtTTD(s), fmtNum(s.CleanPer100(), 2))
	}
}

// Markdown renders the report. It contains no wall-clock times, so the same
// plan and rules produce the same file.
func (rep *Report) Markdown() string {
	var b strings.Builder
	p := rep.Plan
	hours := (p.Duration + p.ClosingWindow).Hours()
	b.WriteString("# Detection quality\n\n")
	b.WriteString("Generated by `make eval` (`go run ./cmd/evaluator`). The evaluator simulates the sessions below in-process, " +
		"runs every event through the ingest stage and the detection engine, exactly as the services do, " +
		"and matches each rule's alerts against the simulator's ground-truth labels. Rerunning it reproduces this file.\n\n")
	b.WriteString("All market data and all abuse are simulated. These numbers measure how well the detectors find the patterns " +
		"TradeWatch itself injects into a synthetic market ([manipulation.md](../../manipulation.md)), not how they would " +
		"perform on a real venue.\n\n")
	b.WriteString("## Setup\n\n| | |\n| --- | --- |\n")
	fmt.Fprintf(&b, "| Sessions with injected abuse | %s of %s of continuous trading and a %s closing phase, seeds %s |\n",
		plural(p.Sessions, "session", "sessions"), fmtDuration(p.Duration), fmtDuration(p.ClosingWindow), rep.seedRange(0, p.Sessions))
	fmt.Fprintf(&b, "| Sessions without abuse | %s of the same length, seeds %s |\n",
		plural(p.Clean, "session", "sessions"), rep.seedRange(p.Sessions, p.Clean))
	fmt.Fprintf(&b, "| Symbols | %d per session, so %.0f symbol-hours with abuse and %.0f without |\n",
		rep.Symbols, float64(rep.Symbols*p.Sessions)*hours, float64(rep.Symbols*p.Clean)*hours)
	in := p.Injection
	fmt.Fprintf(&b, "| Injection | wash trading %g, spoofing %g, momentum ignition %g and quote stuffing %g episodes per symbol-hour; marking the close with probability %g per symbol and session |\n",
		in.WashTrading, in.Spoofing, in.MomentumIgnition, in.QuoteStuffing, in.MarkingTheClose)
	fmt.Fprintf(&b, "| Rules | production `rules/` (digest `%s`), baselines `rules/baselines/` (digest `%s`) |\n",
		short(rep.RulesDigest), short(rep.BaselinesDigest))
	fmt.Fprintf(&b, "| Toolchain | %s |\n\n", rep.GoVersion)
	b.WriteString("**Matching.** An alert matches an episode when it has the same session, symbol and abuse type, at least one " +
		"account in common, was detected no earlier than the episode began, and its evidence window starts no later than one " +
		"minute after the episode ended. Recall counts episodes with at least one matching alert; precision counts alerts on " +
		"sessions with abuse that match an episode. Intervals are 95% Wilson score intervals. Time to detect is simulated " +
		"market time from the episode's first order to the first matching alert.\n\n")

	b.WriteString("## Production rules\n\n")
	qualityTable(&b, rep.Production)
	b.WriteString("\n## Naive baselines\n\n")
	b.WriteString("Each baseline looks only at the single most obvious signal of its abuse type, with the production rule's " +
		"thresholds and suppression period where the signals overlap ([detectors.md](../../detectors.md#evaluation)).\n\n")
	qualityTable(&b, rep.Baseline)

	b.WriteString("\n## Recall by scenario\n\n| Scenario | Abuse type | Episodes | Production recall | Baseline recall |\n| --- | --- | ---: | --- | --- |\n")
	var scenarios []string
	for sc := range rep.Production.ByScenario {
		scenarios = append(scenarios, sc)
	}
	slices.Sort(scenarios)
	for _, sc := range scenarios {
		ps := rep.Production.ByScenario[sc]
		bs := rep.Baseline.ByScenario[sc]
		base := "–"
		if bs != nil {
			base = fmtRate(wilson(bs.Detected, bs.Labels))
		}
		fmt.Fprintf(&b, "| %s | %s | %d | %s | %s |\n", sc, ps.AbuseType, ps.Labels, fmtRate(wilson(ps.Detected, ps.Labels)), base)
	}

	b.WriteString("\n## Parameter sweeps\n\nEach sweep reruns one production rule alone with one threshold changed. " +
		"The production value is marked with an asterisk and a dashed line.\n")
	for _, sw := range rep.Sweeps {
		fmt.Fprintf(&b, "\n### %s: `%s`\n\n![%s %s](%s)\n\n", sw.RuleID, sw.Param, sw.RuleID, sw.Param, sw.PlotFile())
		fmt.Fprintf(&b, "| %s | Recall | Precision | F1 | False alerts per 100 symbol-hours without abuse |\n| --- | --- | --- | ---: | ---: |\n", sw.Param)
		for i, v := range sw.Values {
			s := sw.Points[i].stats(sw.Type)
			mark := ""
			if v == sw.Production {
				mark = " *"
			}
			fmt.Fprintf(&b, "| %s%s | %s | %s | %s | %s |\n", v, mark, fmtRate(s.Recall()), fmtRate(s.Precision()),
				fmtNum(s.F1(), 2), fmtNum(s.CleanPer100(), 2))
		}
	}
	return b.String()
}

// fmtDuration renders a session length, such as "2 h" or "10 min".
func fmtDuration(d time.Duration) string {
	if d%time.Hour == 0 {
		return fmt.Sprintf("%d h", d/time.Hour)
	}
	if d%time.Minute == 0 {
		return fmt.Sprintf("%d min", d/time.Minute)
	}
	return d.String()
}

func plural(n int, one, many string) string {
	if n == 1 {
		return fmt.Sprintf("%d %s", n, one)
	}
	return fmt.Sprintf("%d %s", n, many)
}

func short(digest string) string {
	if len(digest) > 12 {
		return digest[:12]
	}
	return digest
}

// PlotFile is the file name of the sweep's chart.
func (sw SweepResult) PlotFile() string {
	return fmt.Sprintf("sweep-%s-%s.svg", strings.ToLower(sw.RuleID), sw.Param)
}

type rateJSON struct {
	K     int     `json:"k"`
	N     int     `json:"n"`
	Value float64 `json:"value"`
	Lo    float64 `json:"ci95_low"`
	Hi    float64 `json:"ci95_high"`
}

type typeJSON struct {
	Episodes         int       `json:"episodes"`
	Detected         int       `json:"detected"`
	Recall           *rateJSON `json:"recall,omitempty"`
	Alerts           int       `json:"alerts"`
	Matched          int       `json:"matched_alerts"`
	Precision        *rateJSON `json:"precision,omitempty"`
	F1               *float64  `json:"f1,omitempty"`
	TTDMedianS       *float64  `json:"time_to_detect_median_s,omitempty"`
	TTDP90S          *float64  `json:"time_to_detect_p90_s,omitempty"`
	CleanAlerts      int       `json:"clean_alerts"`
	CleanSymbolHours float64   `json:"clean_symbol_hours"`
	CleanPer100      *float64  `json:"clean_alerts_per_100_symbol_hours,omitempty"`
}

func rateOut(r Rate) *rateJSON {
	if !r.Defined() {
		return nil
	}
	return &rateJSON{K: r.K, N: r.N, Value: r.Value, Lo: r.Lo, Hi: r.Hi}
}

func numOut(v float64) *float64 {
	if math.IsNaN(v) {
		return nil
	}
	return &v
}

func typeOut(s *TypeStats) typeJSON {
	out := typeJSON{
		Episodes: s.Labels, Detected: s.Detected, Recall: rateOut(s.Recall()), Alerts: s.Alerts, Matched: s.Matched,
		Precision: rateOut(s.Precision()), F1: numOut(s.F1()), CleanAlerts: s.CleanAlerts,
		CleanSymbolHours: s.CleanSymbolHours, CleanPer100: numOut(s.CleanPer100()),
	}
	if v, ok := s.TTDQuantile(0.5); ok {
		out.TTDMedianS = &v
	}
	if v, ok := s.TTDQuantile(0.9); ok {
		out.TTDP90S = &v
	}
	return out
}

func resultOut(r *Result) map[string]typeJSON {
	out := map[string]typeJSON{}
	for _, t := range TypeNames() {
		out[t] = typeOut(r.stats(t))
	}
	return out
}

// JSON renders every measurement for machines.
func (rep *Report) JSON() ([]byte, error) {
	type sweepPoint struct {
		Value      string   `json:"value"`
		Production bool     `json:"production"`
		Metrics    typeJSON `json:"metrics"`
	}
	type sweepOut struct {
		Rule   string       `json:"rule"`
		Param  string       `json:"param"`
		Type   string       `json:"abuse_type"`
		Points []sweepPoint `json:"points"`
	}
	scen := map[string]map[string]int{}
	for sc, s := range rep.Production.ByScenario {
		scen[sc] = map[string]int{"episodes": s.Labels, "detected": s.Detected}
		if bs := rep.Baseline.ByScenario[sc]; bs != nil {
			scen[sc]["baseline_detected"] = bs.Detected
		}
	}
	doc := map[string]any{
		"plan": map[string]any{
			"first_seed": rep.Plan.FirstSeed, "sessions": rep.Plan.Sessions, "clean_sessions": rep.Plan.Clean,
			"duration": rep.Plan.Duration.String(), "closing_window": rep.Plan.ClosingWindow.String(),
			"injection": rep.Plan.Injection, "symbols": rep.Symbols,
		},
		"rules_digest": rep.RulesDigest, "baselines_digest": rep.BaselinesDigest, "go_version": rep.GoVersion,
		"production": resultOut(rep.Production), "baseline": resultOut(rep.Baseline), "scenarios": scen,
	}
	var sweeps []sweepOut
	for _, sw := range rep.Sweeps {
		so := sweepOut{Rule: sw.RuleID, Param: sw.Param, Type: sw.Type}
		for i, v := range sw.Values {
			so.Points = append(so.Points, sweepPoint{Value: v, Production: v == sw.Production, Metrics: typeOut(sw.Points[i].stats(sw.Type))})
		}
		sweeps = append(sweeps, so)
	}
	doc["sweeps"] = sweeps
	return json.MarshalIndent(doc, "", "  ")
}
