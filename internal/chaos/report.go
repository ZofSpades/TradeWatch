// ParseFaults reads the chaos script's fault log: one fault per line, an
// RFC 3339 time and a description.
func ParseFaults(r io.Reader) ([]Fault, error) {
	var out []Fault
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		at, what, ok := strings.Cut(line, " ")
		t, err := time.Parse(time.RFC3339, at)
		if !ok || err != nil {
			return nil, fmt.Errorf("fault log: bad line %q", line)
		}
		out = append(out, Fault{At: t.UTC(), What: strings.TrimSpace(what)})
	}
	return out, sc.Err()
}

// Write saves the result as results.json and README.md in dir.
func Write(dir string, r *Result) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	js, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "results.json"), append(js, '\n'), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "README.md"), []byte(Markdown(r)), 0o644)
}

func n(v int) string {
	s := fmt.Sprint(v)
	var b strings.Builder
	for i, c := range s {
		if i > 0 && (len(s)-i)%3 == 0 && s[0] != '-' {
			b.WriteByte(',')
		}
		b.WriteRune(c)
	}
	return b.String()
}

// Markdown renders the report.
func Markdown(r *Result) string {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	c := r.Comparison

	p("# Chaos test\n\n")
	p("Generated by `make chaos` on %s UTC", r.Finished.Format("2006-01-02 15:04"))
	if r.Commit != "" {
		p(", at commit `%s`", r.Commit)
	}
	p(". All market data is simulated.\n\n")
	if r.Passed {
		p("**Passed.** The faults below were injected while session `%s` was streaming through the pipeline. Afterwards the pipeline had stored exactly the %s alerts that an offline replay of the session's recording produces:\n\n",
			r.Session, n(c.Expected))
		p("- none missing and none extra;\n- every one with the replay's content;\n- each raised once in the audit trail.\n\n")
		p("The alerts topic carried %s deliveries of the session's alerts, so %s duplicate deliveries reached the alert sink, and the alert key absorbed every one.\n\n",
			n(r.AlertRecords), n(r.AlertRecords-r.AlertKeys))
	} else {
		p("**Failed.** After the faults below, the alerts stored for session `%s` did not match an offline replay of its recording: %d missing, %d unexpected, %d with different content, %d raised more than once.\n\n",
			r.Session, len(c.Missing), len(c.Unexpected), len(c.Differing), len(r.RaisedTwice))
	}

	p("## Faults\n\n")
	p("| Time (UTC) | Fault |\n| --- | --- |\n")
	for _, f := range r.Faults {
		p("| %s | %s |\n", f.At.Format("15:04:05"), f.What)
	}

	p("\n## Outcome\n\n")
	p("| Check | Result |\n| --- | ---: |\n")
	p("| Events in the session's recording | %s |\n", n(r.Events))
	p("| Alerts an offline replay of the recording produces | %s |\n", n(c.Expected))
	p("| Alerts stored for the session | %s |\n", n(c.Stored))
	p("| Expected alerts missing from Postgres | %s |\n", n(len(c.Missing)))
	p("| Stored alerts no replay produces | %s |\n", n(len(c.Unexpected)))
	p("| Stored alerts whose content differs from the replay | %s |\n", n(len(c.Differing)))
	p("| Alerts raised more than once in the audit trail | %s |\n", n(len(r.RaisedTwice)))
	p("| Deliveries of the session's alerts on the alerts topic | %s |\n", n(r.AlertRecords))
	p("| Deliveries the alert sink counted (sum of `deliveries`) | %s |\n", n(r.Deliveries))
	for _, list := range []struct {
		name string
		keys []string
	}{{"Missing", c.Missing}, {"Unexpected", c.Unexpected}, {"Differing", c.Differing}, {"Raised twice", r.RaisedTwice}} {
		if len(list.keys) > 0 {
			p("\n%s: %s\n", list.name, strings.Join(list.keys, ", "))
		}
	}
	if len(r.Recovery) > 0 {
		p("\n## Recovery work\n\n")
		p("Each stage's deduplication counters over the run, from Prometheus. A process killed between two scrapes loses the increments it had not been scraped for, so these are lower bounds.\n\n")
		p("| Counter | Increase |\n| --- | ---: |\n")
		for _, rc := range r.Recovery {
			p("| %s | %s |\n", rc.What, n(int(rc.Increase)))
		}
	}

	p("\n## Method\n\n")
	p("- **Load.** `deploy/compose/chaos.yml` runs marketsim at a fixed rate for one session. Corruption is off, so every published event reaches the detectors, and the session is recorded. Abuse is injected ten times as often as in the demo.\n")
	p("- **Faults.** `scripts/chaos.sh` injects the faults mid-stream with Docker: SIGKILL, graceful restarts and rescaling of the consumers. It also re-publishes exact copies of recent records with `chaos duplicate`.\n")
	p("- **Expected alerts.** When the session has finished and every consumer group has committed up to the end of its input, the recording is replayed offline through ingest's normalization and the detection engine, with the same rules (`internal/replay`).\n")
	p("- **Comparison.** Stored alerts are compared with the replay by alert key and by content. Content excludes what legitimately differs between the two: the wall-clock emission and publication times, the detector instance, and the trace.\n")
	p("- **Deliveries.** These come from the alerts topic itself and from the `deliveries` column the sink increments for every redelivery of a key.\n")
	return b.String()
}
