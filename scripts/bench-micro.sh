#!/usr/bin/env bash
# Runs Go micro-benchmarks and saves the raw `go test -bench` output, with a
# header describing the machine, to docs/results/microbench/<name>.txt, plus a
# benchstat summary (medians and 95% confidence intervals) to
# docs/results/microbench/<name>.benchstat.txt.
#
# Usage: scripts/bench-micro.sh <name> <package> [<package>...]
# Environment: BENCH_COUNT (default 10), BENCH_TIME (default 1s).
set -euo pipefail

BENCHSTAT_VERSION="v0.0.0-20261009192801-be2c69fb417e"

name="$1"
shift
out_dir="docs/results/microbench"
raw="$out_dir/$name.txt"
summary="$out_dir/$name.benchstat.txt"
mkdir -p "$out_dir"

header() {
	echo "# TradeWatch micro-benchmarks: $name"
	echo "# Generated by scripts/bench-micro.sh (make bench-micro)."
	echo "# date:   $(date -u +%Y-%m-%dT%H:%M:%SZ)"
	echo "# commit: $(git -c safe.directory="$PWD" rev-parse --short HEAD 2>/dev/null || echo unknown)"
	echo "# go:     $(go version)"
	echo "# kernel: $(uname -sr)"
	echo "# cpu:    $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | sed 's/^ *//') ($(nproc) logical CPUs visible)"
	echo "# count:  ${BENCH_COUNT:-10} x ${BENCH_TIME:-1s}"
}

{
	header
	echo
	go test -run '^$' -bench . -benchmem -count "${BENCH_COUNT:-10}" -benchtime "${BENCH_TIME:-1s}" "$@"
} | tee "$raw"

{
	header
	echo
	go run "golang.org/x/perf/cmd/benchstat@$BENCHSTAT_VERSION" "$raw"
} >"$summary"

echo "wrote $raw and $summary"
