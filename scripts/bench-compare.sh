#!/usr/bin/env bash
# Compares Go benchmarks between two commits: each is checked out in a
# temporary worktree and benchmarked with the same command, and benchstat
# compares the results (medians of 10 runs, 95% confidence intervals). The
# comparison is saved, with a header describing the machine, to
# docs/results/profiling/<name>.benchstat.txt.
#
# Usage: scripts/bench-compare.sh <name> <old commit> <new commit> <package> <benchmark regexp>
# Environment: BENCH_COUNT (default 10), BENCH_TIME (default 1s).
set -euo pipefail

BENCHSTAT_VERSION="v0.0.0-20261009192801-be2c69fb417e"

name="$1"
old="$2"
new="$3"
pkg="$4"
re="$5"
out="docs/results/profiling/$name.benchstat.txt"
mkdir -p "$(dirname "$out")"
git config --global --add safe.directory "$PWD"
work="$(mktemp -d)"
cleanup() {
	git worktree remove --force "$work/old" 2>/dev/null || true
	git worktree remove --force "$work/new" 2>/dev/null || true
	rm -rf "$work"
}
trap cleanup EXIT

for v in old new; do
	git worktree add --detach "$work/$v" "${!v}" >/dev/null
	(cd "$work/$v" && go test -run '^$' -bench "$re" -benchmem -count "${BENCH_COUNT:-10}" -benchtime "${BENCH_TIME:-1s}" "$pkg") \
		| tee "$work/$v.txt"
done

{
	echo "# TradeWatch benchmark comparison: $name"
	echo "# Generated by scripts/bench-compare.sh (make bench-compare)."
	echo "# date:   $(date -u +%Y-%m-%dT%H:%M:%SZ)"
	echo "# old:    $(git rev-parse --short "$old") $(git log -1 --format=%s "$old")"
	echo "# new:    $(git rev-parse --short "$new") $(git log -1 --format=%s "$new")"
	echo "# go:     $(go version)"
	echo "# cpu:    $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | sed 's/^ *//') ($(nproc) logical CPUs visible)"
	echo "# count:  ${BENCH_COUNT:-10} x ${BENCH_TIME:-1s}"
	echo
	(cd "$work" && go run "golang.org/x/perf/cmd/benchstat@$BENCHSTAT_VERSION" old.txt new.txt)
} >"$out.tmp"
mv "$out.tmp" "$out"
cat "$out"
