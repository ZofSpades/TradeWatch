#!/usr/bin/env bash
# Deploys deploy/k8s to a throwaway single-node k3s cluster in Docker, waits
# for every workload, then runs make demo's scenarios as the demo Job. It
# passes only if each scenario raised an alert that matches its ground
# truth. `make k8s-smoke` runs it after building the images. The cluster
# gets the images from the local Docker, so nothing is pushed to a
# registry. The report goes to docs/results/k8s (K8S_OUT). KEEP=1 leaves
# the cluster running for inspection.
set -euo pipefail

image="${K3S_IMAGE:-rancher/k3s:v1.33.4-k3s1}"
name="tradewatch-k3s"
ns="tradewatch"
out="${K8S_OUT:-docs/results/k8s}"
work="tmp/k8s-smoke"
rm -rf "$work"
mkdir -p "$work"
commit="$(git -c safe.directory="$PWD" rev-parse --short HEAD 2>/dev/null || true)"
started="$(date -u '+%Y-%m-%d %H:%M')"
ready_after=""
passed=0

kubectl() { docker exec -i "$name" kubectl "$@"; }

# until_ok SECONDS WHAT COMMAND... retries COMMAND every 2 s.
until_ok() {
	local limit=$1 what=$2
	shift 2
	local deadline=$((SECONDS + limit))
	until "$@" >/dev/null 2>&1; do
		if ((SECONDS >= deadline)); then
			echo "timed out after ${limit}s waiting for $what" >&2
			return 1
		fi
		sleep 2
	done
}

node_ready() { kubectl get nodes --no-headers | grep -q ' Ready '; }
pod_started() {
	local phase
	phase="$(kubectl -n "$ns" get pods -l job-name=demo -o jsonpath='{.items[0].status.phase}')"
	[ -n "$phase" ] && [ "$phase" != Pending ]
}
job_finished() { [ -n "$(kubectl -n "$ns" get job demo -o jsonpath='{.status.succeeded}{.status.failed}')" ]; }

# The report's backticks are Markdown code spans, not command substitutions.
# shellcheck disable=SC2016
report() {
	mkdir -p "$out"
	{
		echo "# Kubernetes smoke test"
		echo
		printf 'Generated by `make k8s-smoke` on %s UTC' "$started"
		if [ -n "$commit" ]; then printf ', at commit `%s`' "$commit"; fi
		echo ". All market data is simulated."
		echo
		if ((passed)); then
			echo "**Passed.** \`deploy/k8s\` was deployed to a throwaway single-node k3s cluster (\`$image\`) in Docker, with the TradeWatch images built locally. Every workload was available ${ready_after} s after the manifests were applied. Then the demo Job ran the scenarios of \`make demo\`, and each one raised an alert that matches its ground truth."
		else
			echo "**Failed.** \`deploy/k8s\` was deployed to a throwaway single-node k3s cluster (\`$image\`) in Docker. The workloads or the demo Job below did not succeed; \`make k8s-smoke\` printed the pods and recent events."
		fi
		if [ -s "$work/pods.txt" ]; then
			echo
			echo "## Workloads"
			echo
			echo "A service that starts before Kafka accepts connections exits, and Kubernetes starts it again: those are the restarts."
			echo
			echo '```text'
			cat "$work/pods.txt"
			echo '```'
		fi
		if [ -s "$work/demo.txt" ]; then
			echo
			echo "## Demo Job"
			echo
			echo "The output of \`kubectl -n tradewatch logs job/demo\`. Its dashboard links assume \`kubectl -n tradewatch port-forward svc/web 3000:8080\`."
			echo
			echo '```text'
			cat "$work/demo.txt"
			echo '```'
		fi
	} >"$out/README.md"
	echo "report written to $out/README.md"
}

cleanup() {
	local status=$?
	if ((status != 0)); then
		echo "--- pods"
		kubectl -n "$ns" get pods -o wide || true
		echo "--- recent events"
		kubectl -n "$ns" get events --sort-by=.lastTimestamp | tail -n 30 || true
	fi
	report
	if [ "${KEEP:-0}" = 1 ]; then
		echo "the cluster is still running: docker exec -it $name kubectl -n $ns get pods"
	else
		docker rm -f "$name" >/dev/null 2>&1 || true
	fi
	exit "$status"
}
trap cleanup EXIT

echo "starting k3s ($image)"
docker rm -f "$name" >/dev/null 2>&1 || true
docker run -d --name "$name" --privileged --tmpfs /run --tmpfs /var/run "$image" \
	server --disable=traefik --disable=metrics-server >/dev/null
until_ok 180 "the node to be ready" node_ready
docker cp deploy/k8s "$name:/manifests"

# The cluster gets every image the manifests use that Docker has: the
# TradeWatch images exist only here, and the others then need no download.
mapfile -t images < <(kubectl kustomize /manifests | sed -n 's/^ *image: //p' | sort -u)
present=()
for img in "${images[@]}"; do
	if docker image inspect "$img" >/dev/null 2>&1; then
		present+=("$img")
	fi
done
echo "loading ${#present[@]} of ${#images[@]} images into the cluster: ${present[*]}"
docker save "${present[@]}" | docker exec -i "$name" ctr -n k8s.io images import - >/dev/null

echo "deploying deploy/k8s"
kubectl apply -f /manifests/namespace.yaml >/dev/null
kubectl -n "$ns" create secret generic tradewatch --from-env-file=/dev/stdin <.env >/dev/null
applied=$SECONDS
kubectl apply -k /manifests >/dev/null
kubectl -n "$ns" rollout status statefulset/kafka --timeout=5m
kubectl -n "$ns" rollout status statefulset/postgres --timeout=5m
kubectl -n "$ns" wait --for=condition=Available deployment --all --timeout=10m
ready_after=$((SECONDS - applied))
kubectl -n "$ns" get pods | tee "$work/pods.txt"

echo "running the demo Job"
kubectl apply -k /manifests/demo >/dev/null
until_ok 300 "the demo pod to start" pod_started
kubectl -n "$ns" logs -f job/demo | tee "$work/demo.txt"
until_ok 60 "the demo Job to finish" job_finished
if [ "$(kubectl -n "$ns" get job demo -o jsonpath='{.status.succeeded}')" != 1 ]; then
	echo "the demo Job failed" >&2
	exit 1
fi
passed=1
echo "Kubernetes smoke test passed"
