#!/usr/bin/env sh
# Creates or completes the local .env file with randomly generated secrets.
#
# The file is git-ignored and is only meant for running the stack locally.
# Existing values are never changed; variables that are missing (for example
# after pulling a version that needs a new secret) are appended.
set -eu

ENV_FILE="${1:-.env}"

rand_hex() {
	# $1 = number of random bytes
	head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
}

umask 077
if [ ! -f "$ENV_FILE" ]; then
	printf '# Generated by scripts/init-env.sh. Local development only; never commit.\n' >"$ENV_FILE"
	echo "created $ENV_FILE"
fi

ensure() {
	if ! grep -q "^$1=" "$ENV_FILE"; then
		printf '%s=%s\n' "$1" "$2" >>"$ENV_FILE"
		echo "added $1 to $ENV_FILE"
	fi
}

ensure POSTGRES_PASSWORD "$(rand_hex 16)"
ensure TW_API_JWT_SECRET "$(rand_hex 32)"
ensure TW_API_ANALYST_PASSWORD "$(rand_hex 12)"
ensure TW_API_ADMIN_PASSWORD "$(rand_hex 12)"
ensure GRAFANA_ADMIN_PASSWORD "$(rand_hex 12)"
